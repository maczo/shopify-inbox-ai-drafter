/**
 * Generates promptfoo/promptfooconfig.yaml from the data files, so the harness
 * can never drift from questions.json / golden.json.
 *
 *   npm run promptfoo:gen
 *   npx promptfoo eval --filter-metadata subset=verified
 *
 * The config below is the canonical, reviewable assertion set. `npm run grade`
 * executes the same assertions with a resumable, rate-limited runner and writes
 * the per-row data the report needs.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = <T,>(p: string): T => JSON.parse(readFileSync(join(root, p), "utf8")) as T;

type Question = { id: string; productId: string; text: string };
type Golden = { questionId: string; productId: string; verdict: string };

const questions = read<Question[]>("data/questions.json");
const golden = read<Golden[]>("data/golden.json");
const goldenById = new Map(golden.map((g) => [g.questionId, g]));

const judge = process.env.JUDGE_MODEL ?? "recursive/flint-v1.0:free";
const base = process.env.BASE_URL ?? "http://localhost:3000";

const q = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

const tests = questions
  .map((question) => {
    const gold = goldenById.get(question.id);
    const lines = [
      `  - vars:`,
      `      questionId: ${q(question.id)}`,
      `      productId: ${q(question.productId)}`,
      `      message: ${q(question.text)}`,
      `    metadata:`,
      `      subset: ${gold ? "verified" : "unverified"}`,
      `      sheetRow: ${Number(question.id.split("-")[1]) + 1}`,
    ];
    if (gold) {
      lines.push(`    assert:`);
      lines.push(`      - type: javascript`);
      lines.push(`        value: |`);
      lines.push(`          const r = JSON.parse(output);`);
      lines.push(`          return r.verdict === ${q(gold.verdict)};`);
    }
    return lines.join("\n");
  })
  .join("\n");

const yaml = `# GENERATED by scripts/make-promptfoo.ts — do not edit by hand.
# Regenerate with: npm run promptfoo:gen
description: "Shopify Inbox AI Drafter — 120 shopper replies"

prompts:
  - "{{message}}"

providers:
  - id: http
    config:
      url: ${base}/api/draft
      method: POST
      headers:
        Content-Type: application/json
      body:
        productId: "{{productId}}"
        message: "{{message}}"
      transformResponse: json

defaultTest:
  assert:
    - type: is-json
    - type: not-regex
      value: "\\\\[(?:coconut-derived|also known as):"
    - type: not-regex
      value: "As an AI|\\\\[name\\\\]|\\\\*\\\\*|https?://"
    - type: javascript
      value: |
        const r = JSON.parse(output);
        if (!['answered', 'flagged'].includes(r.verdict)) return false;
        if (r.verdict === 'answered') {
          if (!r.evidence || r.evidence.length === 0) return false;
          return r.evidence.every(e => e.ok === true);
        }
        return true;
    - type: javascript
      value: |
        const r = JSON.parse(output);
        if (r.verdict !== 'flagged') return true;
        const t = (r.draft || '').trim();
        if (!t || t.split(/\\s+/).length > 60) return false;
        if (/\\d|\\$/.test(t)) return false;
        if (/\\b(ingredients?|contains?|lanolin|coconut|shea|beeswax|retinol|almond|fragrance|shipping|refund|returns?|stock|size|ml|grams?)\\b/i.test(t)) return false;
        return /(check|confirm|look into|get back|come back|follow up|ask the team)/i.test(t);
    - type: llm-rubric
      threshold: 1
      provider: openrouter:${judge}
      value: >
        Every factual claim in this reply is supported by the product document.
        A claim of absence ("does not contain", "free of", "safe for") is
        supported only if the document states it. A reply that says the merchant
        will check and follow up makes no claim and passes.
    - type: llm-rubric
      threshold: 0.9
      provider: openrouter:${judge}
      value: >
        A merchant could send this reply to the shopper unchanged: it is
        accurate, answers what was asked, is polite, and contains no
        placeholders or mention of being an assistant.

evaluateOptions:
  maxConcurrency: 3

tests:
${tests}
`;

mkdirSync(join(root, "promptfoo"), { recursive: true });
writeFileSync(join(root, "promptfoo/promptfooconfig.yaml"), yaml);
console.log(
  `wrote promptfoo/promptfooconfig.yaml — ${questions.length} tests ` +
    `(${golden.length} verified, ${questions.length - golden.length} unverified)`,
);
